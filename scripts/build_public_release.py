def is_placeholder(value):
    v = value.strip().strip('\'"').lower()
    if not v:
        return True
    if v.startswith(('$', '{{', '%', '<')) or '<' in v or '>' in v:
        return True
    if any(w in v for w in PLACEHOLDER_WORDS):
        return True
    core = re.sub(r'[^a-z0-9]', '', v)
    return len(set(core)) <= 3


def _post_generic(m, line):
    if re.search(r'(?i)(sha\d*|hash|digest|checksum|fingerprint)', m.group('k')):
        return False
    value = m.group('v')
    if not (re.search(r'[A-Za-z]', value) and re.search(r'\d', value)):
        return False
    return line[m.end('v'):m.end('v') + 1] != '('


