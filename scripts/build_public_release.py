class Refused(Exception):
    pass


LABEL_RE = re.compile(r'^[A-Za-z0-9][A-Za-z0-9._-]{0,40}$')


def utc_stamp():
    return datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ')


def resolve_target(args):
    name = args.name
    if args.version and args.new_dest:
        raise Refused('--version and --new-dest are mutually exclusive')
    if not LABEL_RE.match(name):
        raise Refused('invalid --name')
    if args.version:
        if not LABEL_RE.match(args.version):
            raise Refused('invalid --version label')
        name = '%s-%s' % (name, args.version)
    elif args.new_dest:
        name = '%s-%s' % (name, utc_stamp())
    if os.path.lexists(RELEASE_DIR) and is_reparse(RELEASE_DIR):
        raise Refused('release/ is a link; refusing')
    return RELEASE_DIR / name, RELEASE_DIR / (name + '.zip'), name


def check_replaceable(dest, zip_path, name, allow):
    if os.path.lexists(dest):
        if is_reparse(dest) or not dest.is_dir():
            raise Refused('existing target is not a plain directory: refusing --force')
        res = verify_package(dest, allow, deep=False)
        if not res['ok']:
            raise Refused('existing target does not verify as an unmodified earlier build (%s); '
                          'use --version/--new-dest instead' % ', '.join(sorted({p['kind'] for p in res['problems']})))
    if os.path.lexists(zip_path):
        if is_reparse(zip_path) or not zipfile.is_zipfile(zip_path):
            raise Refused('existing ZIP is not a plain ZIP file: refusing --force')
        with zipfile.ZipFile(zip_path) as zf:
            names = zf.namelist()
        if not names or any(not n.startswith(name + '/') for n in names) or \
                (name + '/' + MANIFEST_NAME) not in names:
            raise Refused('existing ZIP is not an earlier build of this tool: refusing --force')


def publish(pairs, force):
    """pairs: [(tmp_path, final_path)]. Existing finals are moved aside (never deleted), only with force."""
    moved, placed = [], []
    stamp = utc_stamp()
    try:
        for _, target in pairs:
            if os.path.lexists(target):
                if not force:
                    raise Refused('target appeared during build: %s' % target.name)
                aside = target.with_name(target.name + '.replaced-' + stamp)
                if os.path.lexists(aside):
                    raise Refused('aside name already exists: %s' % aside.name)
                os.rename(target, aside)
                moved.append((aside, target))
        for tmp, target in pairs:
            os.rename(tmp, target)
            placed.append((tmp, target))
    except BaseException:
        for tmp, target in reversed(placed):
            os.rename(target, tmp)
        for aside, target in reversed(moved):
            if not os.path.lexists(target):
                os.rename(aside, target)
        raise
    return [a.name for a, _ in moved]


def safe_rmtree(path):
    p = Path(path)
    if p.parent == RELEASE_DIR and p.name.startswith('.stage-') and p.exists() and not is_reparse(p):
        shutil.rmtree(p, ignore_errors=True)


def summarize_selection(ctx):
    by_rule = {}
    for rule in ctx.selected.values():
        by_rule[rule] = by_rule.get(rule, 0) + 1
    return {
        'files_selected': len(ctx.selected),
        'by_rule': dict(sorted(by_rule.items())),
        'missing_required': ctx.missing_required,
        'optional_absent': ctx.optional_absent,
        'excluded_by_rule': sorted(ctx.excluded, key=lambda e: (e['rule'], e['path'])),
        'skipped_by_suffix': dict(sorted(ctx.skipped.items())),
        'pruned_dirs': dict(sorted(ctx.pruned.items())),
        'link_violations': sorted(set(ctx.link_violations)),
        'oversize': ctx.oversize,
        'unreadable': ctx.unreadable,
        'overrides': dict(sorted(ctx.sources.items())),
        'withheld': sorted(ctx.withheld),
    }


def selection_problems(ctx):
    problems = []
    for item in ctx.missing_required:
        problems.append(dict(kind='missing_required', **item))
    for rel in sorted(set(ctx.link_violations)):
        problems.append({'kind': 'link_in_allowlisted_tree', 'path': rel})
    for item in ctx.oversize:
        problems.append({'kind': 'oversize', 'path': item['path']})
    for rel in ctx.unreadable:
        problems.append({'kind': 'unreadable', 'path': rel})
    return problems


def cmd_plan(args):
    ctx = Ctx(args.evidence)
    collect(ctx)
    apply_withholds(ctx, args.withhold)
    apply_overrides(ctx, args.override)
    allow, allow_hash = load_scan_allow(args.scan_allow)
    items = [(rel, source_of(ctx, rel)) for rel in sorted(ctx.selected)]
    findings = scan_files(items, allow)
    md = [(r, p) for r, p in items if r.endswith('.md')]
    links = check_links(md, set(ctx.selected))
    problems = selection_problems(ctx)
    for f in blocked(findings):
        problems.append({'kind': 'secret_scan_blocked', 'path': f['path'], 'rule': f['rule'], 'lines': f['lines']})
    if args.strict_links and links['missing']:
        problems.append({'kind': 'missing_links', 'count': len(links['missing'])})
    report = {'command': 'plan', 'ok': not problems, 'selection': summarize_selection(ctx),
              'scan': findings, 'links': links, 'problems': problems,
              'license_file_present': any(r in ctx.selected for r in ('LICENSE', 'LICENSE.md', 'LICENSE.txt'))}
    if args.list_files:
        report['files'] = sorted(ctx.selected.items())
    emit(report)
    return 0 if not problems else 3


def cmd_build(args):
    try:
        dest, zip_path, name = resolve_target(args)
        allow, allow_hash = load_scan_allow(args.scan_allow)
        sidecar_final = RELEASE_DIR / (name + '.zip.sha256')
        exists = [p.name for p in (dest, zip_path, sidecar_final) if os.path.lexists(p)]
        if os.path.lexists(sidecar_final) and (is_reparse(sidecar_final) or not sidecar_final.is_file()):
            raise Refused('existing .sha256 is not a plain file')
        if exists and not args.force:
            raise Refused('target exists (%s); not overwriting. Use --version LABEL, --new-dest, or '
                          '--force (verified, moves old aside)' % ', '.join(exists))
        if exists:
            check_replaceable(dest, zip_path, name, allow)
    except (Refused, ValueError, OSError) as exc:
        emit({'command': 'build', 'ok': False, 'refused': str(exc)})
        return 2

    ctx = Ctx(args.evidence)
    collect(ctx)
    apply_withholds(ctx, args.withhold)
    apply_overrides(ctx, args.override)
    problems = selection_problems(ctx)
    base = {'command': 'build', 'target': dest.name, 'zip': zip_path.name,
            'selection': summarize_selection(ctx)}
    if problems:
        emit(dict(base, ok=False, blocked_before_copy=True, problems=problems))
        return 3

    RELEASE_DIR.mkdir(exist_ok=True)
    stage = RELEASE_DIR / ('.stage-%s-%d' % (name, os.getpid()))
    zip_tmp = RELEASE_DIR / ('.stage-%s-%d.zip' % (name, os.getpid()))
    sidecar_tmp = RELEASE_DIR / ('.stage-%s-%d.zip.sha256' % (name, os.getpid()))
    sidecar = RELEASE_DIR / (name + '.zip.sha256')
    if any(os.path.lexists(p) for p in (stage, zip_tmp, sidecar_tmp)):
        emit(dict(base, ok=False, refused='stale staging path exists: %s' % stage.name))
        return 2
    try:
        stage.mkdir()
        entries = []
        for rel in sorted(ctx.selected):
            src = source_of(ctx, rel)
            dst = stage / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            before = sha256_file(src)
            shutil.copyfile(src, dst)
            after = sha256_file(dst)
            if before != after or sha256_file(src) != before:
                problems.append({'kind': 'copy_not_identical', 'path': rel})
                continue
            entries.append({'path': rel, 'size': dst.stat().st_size, 'sha256': after,
                            'rule': ctx.selected[rel],
                            'source': 'override:' + ctx.sources[rel] if rel in ctx.sources else 'repo',
                            'byte_identical_to_source': True})
        (stage / '.gitignore').write_bytes(SAFE_GITIGNORE.encode('utf-8'))
        entries.append({'path': '.gitignore', 'size': len(SAFE_GITIGNORE.encode('utf-8')),
                        'sha256': sha256_bytes(SAFE_GITIGNORE.encode('utf-8')), 'rule': 'generated_gitignore',
                        'source': 'generated', 'byte_identical_to_source': None})
        (stage / '.gitattributes').write_bytes(SAFE_GITATTRIBUTES.encode('utf-8'))
        entries.append({'path': '.gitattributes', 'size': len(SAFE_GITATTRIBUTES.encode('utf-8')),
                        'sha256': sha256_bytes(SAFE_GITATTRIBUTES.encode('utf-8')), 'rule': 'generated_gitattributes',
                        'source': 'generated', 'byte_identical_to_source': None})
        if problems:
            emit(dict(base, ok=False, problems=problems))
            return 3
        findings = scan_files(((e['path'], stage / e['path']) for e in entries), allow)
        for f in blocked(findings):
            problems.append({'kind': 'secret_scan_blocked', 'path': f['path'], 'rule': f['rule'],
                             'lines': f['lines']})
        md = [(e['path'], stage / e['path']) for e in entries if e['path'].endswith('.md')]
        links = check_links(md, {e['path'] for e in entries})
        if args.strict_links and links['missing']:
            problems.append({'kind': 'missing_links', 'count': len(links['missing'])})
        if problems:
            emit(dict(base, ok=False, problems=problems, scan=findings, links=links))
            return 3
        license_present = any(e['path'] in ('LICENSE', 'LICENSE.md', 'LICENSE.txt') for e in entries)
        manifest = {
            'schema': SCHEMA, 'generator': GENERATOR, 'package': name,
            'status': 'review_candidate_not_published',
            'generated_at_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds'),
            'python': sys.version.split()[0],
            'license': {'file_present': license_present,
                        'status': 'present_unreviewed' if license_present else 'pending'},
            'evidence_mode': args.evidence,
            'file_count': len(entries),
            'content_digest_sha256': content_digest(entries),
            'files': sorted(entries, key=lambda e: e['path']),
            'selection': summarize_selection(ctx),
            'scan': {'rule_ids': sorted(SCAN_RULE_IDS), 'scan_allow_sha256': allow_hash,
                     'findings_not_blocking': findings,
                     'note': 'Findings list path/rule/line only; values are never recorded.'},
            'links': links,
            'notes': ['Public evidence reports are copied byte-for-byte; they are not re-signed or re-hashed.',
                      'Review candidate only; nothing here has been published.'],
        }
        manifest_bytes = (json.dumps(manifest, indent=2, ensure_ascii=True, sort_keys=True) + '\n').encode('utf-8')
        (stage / MANIFEST_NAME).write_bytes(manifest_bytes)
        sum_entries = [dict(e) for e in entries] + [{'path': MANIFEST_NAME, 'sha256': sha256_bytes(manifest_bytes)}]
        (stage / SUMS_NAME).write_text(sums_text(sum_entries), encoding='utf-8', newline='\n')

        check = verify_package(stage, allow, deep=True, strict_links=args.strict_links)
        if not check['ok']:
            emit(dict(base, ok=False, problems=check['problems']))
            return 3
        all_rels = [e['path'] for e in entries] + [MANIFEST_NAME, SUMS_NAME]
        write_zip(stage, all_rels, zip_tmp, name)
        expected = {r: sha256_file(stage / r) for r in all_rels}
        zproblems = verify_zip(zip_tmp, expected, name)
        if zproblems:
            emit(dict(base, ok=False, problems=zproblems))
            return 3
        zip_hash = sha256_file(zip_tmp)
        sidecar_tmp.write_text('%s  %s\n' % (zip_hash, zip_path.name), encoding='utf-8', newline='\n')
        replaced = publish([(stage, dest), (zip_tmp, zip_path), (sidecar_tmp, sidecar)], args.force)
    except Refused as exc:
        emit(dict(base, ok=False, refused=str(exc)))
        return 2
    finally:
        safe_rmtree(stage)
        for leftover in (zip_tmp, sidecar_tmp):
            if os.path.lexists(leftover):
                try:
                    os.remove(leftover)
                except OSError:
                    pass
    report = dict(base, ok=True, status='review_candidate_not_published', files=len(all_rels),
                  content_digest_sha256=manifest['content_digest_sha256'], zip_sha256=zip_hash,
                  replaced_aside=replaced, scan=findings, links=links,
                  license_pending=not license_present,
                  optional_absent=ctx.optional_absent)
    emit(report)
    return 0


def cmd_verify(args):
    try:
        allow, _ = load_scan_allow(args.scan_allow)
        if args.name and not LABEL_RE.match(args.name):
            raise Refused('invalid --name')
    except (Refused, ValueError, OSError) as exc:
        emit({'command': 'verify', 'ok': False, 'refused': str(exc)})
        return 2
    dest = Path(args.dest) if args.dest else RELEASE_DIR / args.name
    dest = dest if dest.is_absolute() else Path.cwd() / dest
    if not dest.is_dir() or is_reparse(dest):
        emit({'command': 'verify', 'ok': False, 'refused': 'package directory missing or not a plain directory'})
        return 2
    zip_path = Path(args.zip) if args.zip else dest.with_name(dest.name + '.zip')
    zip_arg = zip_path if os.path.isfile(zip_path) else None
    if args.zip and zip_arg is None:
        emit({'command': 'verify', 'ok': False, 'refused': 'ZIP not found'})
        return 2
    res = verify_package(dest, allow, deep=True, strict_links=args.strict_links, zip_path=zip_arg)
    res['command'] = 'verify'
    res['zip_checked'] = zip_arg is not None
    emit(res)
    return 0 if res['ok'] else 3


def emit(obj):
    sys.stdout.write(json.dumps(obj, indent=2, ensure_ascii=True, sort_keys=False) + '\n')


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    sub = parser.add_subparsers(dest='command', required=True)

    def common(p):
        p.add_argument('--evidence', choices=('always', 'none'), default='always',
                       help='include the four already-public JSON evidence reports (byte-identical)')
        p.add_argument('--scan-allow', help='reviewed JSON list of {path, rule, reason} scan allowances')
        p.add_argument('--strict-links', action='store_true', help='treat missing relative links as blocking')
        p.add_argument('--override', action='append', metavar='PKG=SRC',
                       help='ship repo file SRC at package path PKG (PKG must be selected by a rule); repeatable')
        p.add_argument('--withhold', action='append', metavar='PKG',
                       help='do not ship package path PKG although a rule selects it; repeatable')

    plan = sub.add_parser('plan', help='dry run')
    common(plan)
    plan.add_argument('--list-files', action='store_true')
    build = sub.add_parser('build')
    common(build)
    build.add_argument('--name', default=DEFAULT_NAME)
    build.add_argument('--version', help='label appended to the target name (release/<name>-<label>)')
    build.add_argument('--new-dest', action='store_true', help='append a UTC timestamp to the target name')
    build.add_argument('--force', action='store_true',
                       help='replace an existing target only if it verifies as an unmodified earlier build; '
                            'the old one is moved aside, not deleted')
    verify = sub.add_parser('verify')
    verify.add_argument('--dest', help='package directory (default release/<name>)')
    verify.add_argument('--name', default=DEFAULT_NAME)
    verify.add_argument('--zip', help='ZIP to compare (default <dest>.zip if present)')
    verify.add_argument('--scan-allow')
    verify.add_argument('--strict-links', action='store_true')
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    try:
        if args.command == 'plan':
            return cmd_plan(args)
        if args.command == 'build':
            return cmd_build(args)
        return cmd_verify(args)
    except ValueError as exc:
        emit({'command': args.command, 'ok': False, 'refused': str(exc)})
        return 2


if __name__ == '__main__':
    sys.exit(main())
