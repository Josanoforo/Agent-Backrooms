def _marker_rules(line, kind):
    out = set()
    for m in MARK_RE.finditer(line):
        if m.group(1) == kind:
            out.update(m.group(2).split(','))
    return out


def load_scan_allow(path):
    if not path:
        return {}, None
    p = Path(path)
    data = json.loads(p.read_text(encoding='utf-8'))
    if not isinstance(data, list):
        raise ValueError('scan-allow file must be a JSON list')
    allow = {}
    for i, item in enumerate(data):
        rel = item.get('path', '') if isinstance(item, dict) else ''
        rule = item.get('rule', '') if isinstance(item, dict) else ''
        reason = item.get('reason', '') if isinstance(item, dict) else ''
        if (not rel or rel.startswith('/') or '..' in rel.split('/') or '\\' in rel
                or rule not in SCAN_RULE_IDS or not str(reason).strip()):
            raise ValueError('scan-allow entry %d needs relative posix path, known rule and non-empty reason' % i)
        allow[(rel, rule)] = reason
    return allow, sha256_file(p)


def scan_file(rel, path, allow):
    """Return list of (rule, line or None, severity, disposition)."""
    data = path.read_bytes()
    binary = _suffix(rel) in BIN_SUFFIXES or b'\x00' in data[:8192]
    out = []

    def disposition(rule_id, ph_aware, value, line, prev, file_marks):
        if ph_aware and is_placeholder(value):
            return 'allowed_placeholder'
        if rule_id in file_marks or (line is not None and (
                rule_id in _marker_rules(line, 'allow') or rule_id in _marker_rules(prev, 'allow'))):
            return 'allowed_marker'
        if (rel, rule_id) in allow:
            return 'allowed_allowlist'
        return 'blocked'

    if binary:
        text = data.decode('latin-1')
        for rule_id, rx, strict, ph, post, sev in SECRET_RULES:
            if not strict:
                continue
            for m in rx.finditer(text):
                value = m.group('v') if 'v' in rx.groupindex else m.group(0)
                out.append((rule_id, None, sev, disposition(rule_id, ph, value, None, '', set())))
        return out
    lines = data.decode('utf-8', 'replace').splitlines()
    file_marks = set()
    for head in lines[:30]:
        file_marks |= _marker_rules(head, 'allow-file')
    for i, line in enumerate(lines, 1):
        prev = lines[i - 2] if i > 1 else ''
        for rule_id, rx, strict, ph, post, sev in SECRET_RULES:
            for m in rx.finditer(line):
                if post and not post(m, line):
                    continue
                if sev == 'warning':
                    out.append((rule_id, i, sev, 'warning'))
                    continue
                value = m.group('v') if 'v' in rx.groupindex else m.group(0)
                out.append((rule_id, i, sev, disposition(rule_id, ph, value, line, prev, file_marks)))
    return out


def scan_files(items, allow):
    """items: iterable of (rel, Path). Returns aggregated findings list (no values)."""
    agg = {}
    for rel, path in items:
        for rule_id, line, sev, disp in scan_file(rel, path, allow):
            agg.setdefault((rel, rule_id, sev, disp), []).append(line)
    findings = []
    for (rel, rule_id, sev, disp), lines in sorted(agg.items()):
        nums = sorted({n for n in lines if n is not None})
        findings.append({'path': rel, 'rule': rule_id, 'severity': sev, 'disposition': disp,
                         'count': len(lines), 'lines': nums[:25]})
    return findings


def blocked(findings):
    return [f for f in findings if f['disposition'] == 'blocked']


# ---------------------------------------------------------------------------------------------
# Relative link check for included Markdown (documents gaps, never adds files)
# ---------------------------------------------------------------------------------------------
LINK_RE = re.compile(r'!?\[[^\]]*\]\(\s*(<[^>]+>|[^)\s]+)(?:\s+(?:"[^"]*"|\'[^\']*\'))?\s*\)')
REFDEF_RE = re.compile(r'^\s{0,3}\[[^\]]+\]:\s*(<[^>]+>|\S+)')
SCHEME_RE = re.compile(r'^[A-Za-z][A-Za-z0-9+.-]*:')


def check_links(md_items, fileset):
    """md_items: iterable of (rel, Path). fileset: set of package-relative file paths."""
    dirs = set()
    for rel in fileset:
        parts = rel.split('/')
        for i in range(1, len(parts)):
            dirs.add('/'.join(parts[:i]))
    ok = external = anchors = 0
    missing = []
    for rel, path in md_items:
        in_fence = False
        for lineno, line in enumerate(path.read_text(encoding='utf-8', errors='replace').splitlines(), 1):
            stripped = line.lstrip()
            if stripped.startswith(('```', '~~~')):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            scrubbed = re.sub(r'`[^`]*`', '', line)
            targets = [m.group(1) for m in LINK_RE.finditer(scrubbed)]
            ref = REFDEF_RE.match(scrubbed)
            if ref:
                targets.append(ref.group(1))
            for raw in targets:
                target = raw.strip('<>')
                if SCHEME_RE.match(target):
                    external += 1
                    continue
                target = unquote(target.split('#', 1)[0].split('?', 1)[0])
                if not target:
                    anchors += 1
                    continue
                resolved = posixpath.normpath(posixpath.join(posixpath.dirname(rel), target))
                if resolved in fileset or resolved in dirs:
                    ok += 1
                    continue
                if resolved.startswith('..') or resolved.startswith('/'):
                    status = 'outside_package'
                elif os.path.lexists(ROOT / resolved):
                    status = 'exists_in_repo_not_in_package'
                else:
                    status = 'absent_in_repo'
                missing.append({'source': rel, 'line': lineno, 'target': target, 'status': status})
    return {'ok': ok, 'external_skipped': external, 'anchor_only_skipped': anchors,
            'missing': missing}


