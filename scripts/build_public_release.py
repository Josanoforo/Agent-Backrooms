#!/usr/bin/env python3
"""Build a reviewable PUBLIC package (directory + ZIP) from an explicit allowlist. Stdlib only.

This prepares a candidate for human review. It does not publish anything, never talks to the
network or git, never reads .private/ or real .env files, and never prints matched secret values
(findings are reported by path / rule / line number only).

  build_public_release.py plan   [options]   dry run: selection, exclusions, scan, links
  build_public_release.py build  [options]   write release/<name>/ and release/<name>.zip
  build_public_release.py verify [options]   re-check an existing package (and optionally its ZIP)

Target policy (build): the default target is release/ola5-public(.zip). If either already exists the
build is REFUSED (exit 2). Choose another target with --version LABEL or --new-dest (UTC stamp), or
pass --force: the existing target must first verify as an unmodified earlier build of this tool, and
it is then moved aside to '<name>.replaced-<UTC stamp>' (never deleted) only after the new build
passed every check. Output is staged in release/.stage-* and renamed into place at the end.

Exit status: 0 ok, 2 refused (target exists / bad arguments), 3 blocked (rule, scan or verification
failure; nothing is left at the target).

Scan allowances (never silent, always listed per path/rule):
  * placeholder values (empty, 'changeme', '<...>', 'your-...', ${VAR}, low-entropy 'xxxx') ;
  * a marker on the same or previous line:   public-scan: allow <rule_id>[,<rule_id>] -- <reason>
    or near the top of a file:               public-scan: allow-file <rule_id> -- <reason>
  * --scan-allow FILE.json: list of {"path": "...", "rule": "...", "reason": "..."}; its SHA-256
    is recorded in the manifest. Intended for reviewed test doubles/fixtures that cannot hold comments.

Overrides (plan/build): --override PKG=SRC ships the repo file SRC at package path PKG (repeatable).
PKG must already be selected by a rule and keep its suffix; SRC must be a plain, non-denied repo file.
Use it for a package-specific variant of a document whose repo version links to files that do not
travel (e.g. README.md). The manifest records 'source': 'override:<SRC>' for such entries.
"""
