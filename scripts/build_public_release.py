def is_pruned_dir(name):
    return name in PRUNE_DIR_NAMES or name.startswith('.venv')


def deny_reason(rel):
    parts = rel.split('/')
    for part in parts[:-1]:
        if part.lower() in DENY_DIR_PARTS or part.lower().startswith('.venv'):
            return 'denied_dir:' + part
    name = parts[-1]
    low = name.lower()
    if low == '.env' or (low.startswith('.env.') and low != '.env.example'):
        return 'env_file'
    if low.endswith(KEY_SUFFIXES) or low.startswith(('id_rsa', 'id_ed25519', 'id_ecdsa')):
        return 'key_material'
    if DB_RE.search(low):
        return 'database_file'
    if low.endswith(('.pyc', '.pyo')):
        return 'bytecode'
    if low.endswith('.log'):
        return 'log_file'
    if low.startswith(('credentials', '.netrc', '.npmrc', '.pypirc')):
        return 'credential_file'
    if parts[0] in ('infra', 'scripts') and OPS_NAME_RE.search(name):
        return 'private_ops_name'
    return None


def rule_for(rel):
    for rule in RULES:
        if rel in rule.get('exact', ()):
            return rule['id']
        for root in rule.get('roots', ()):
            if rel.startswith(root + '/') and rule['match'](rel):
                if not rule.get('recursive', True) and '/' in rel[len(root) + 1:]:
                    continue
                if rel.startswith(tuple(rule.get('exclude_prefixes', ()))):
                    continue
                return rule['id']
    return None


