def content_digest(entries):
    digest = hashlib.sha256()
    for e in sorted(entries, key=lambda x: x['path']):
        digest.update(('%s\0%s\n' % (e['path'], e['sha256'])).encode('utf-8'))
    return digest.hexdigest()


def sums_text(entries):
    return ''.join('%s  %s\n' % (e['sha256'], e['path']) for e in sorted(entries, key=lambda x: x['path']))


def write_zip(pkg_dir, rels, zip_path, prefix):
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for rel in sorted(rels):
            info = zipfile.ZipInfo('%s/%s' % (prefix, rel), date_time=ZIP_EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o100644 << 16
            zf.writestr(info, (pkg_dir / rel).read_bytes())


def verify_zip(zip_path, expected, prefix=None):
    """expected: {rel: sha256}. Returns list of problems."""
    problems = []
    try:
        zf = zipfile.ZipFile(zip_path)
    except (OSError, zipfile.BadZipFile) as exc:
        return [{'kind': 'zip_unreadable', 'detail': type(exc).__name__}]
    with zf:
        bad = zf.testzip()
        if bad:
            problems.append({'kind': 'zip_crc_error', 'path': bad})
        names = [i.filename for i in zf.infolist()]
        if len(names) != len(set(names)):
            problems.append({'kind': 'zip_duplicate_entries'})
        tops = {n.split('/', 1)[0] for n in names}
        if prefix is None and len(tops) == 1:
            prefix = next(iter(tops))
        if prefix is None or tops != {prefix}:
            problems.append({'kind': 'zip_bad_top_level', 'found': sorted(tops)[:5]})
            return problems
        got = {}
        for info in zf.infolist():
            n = info.filename
            if n.startswith('/') or '\\' in n or '..' in n.split('/'):
                problems.append({'kind': 'zip_unsafe_entry', 'path': n})
                continue
            if ((info.external_attr >> 16) & 0o170000) == 0o120000:
                problems.append({'kind': 'zip_symlink_entry', 'path': n})
                continue
            if n.endswith('/'):
                continue
            got[n[len(prefix) + 1:]] = sha256_bytes(zf.read(info))
        for rel in sorted(set(expected) - set(got)):
            problems.append({'kind': 'zip_missing', 'path': rel})
        for rel in sorted(set(got) - set(expected)):
            problems.append({'kind': 'zip_extra', 'path': rel})
        for rel in sorted(set(got) & set(expected)):
            if got[rel] != expected[rel]:
                problems.append({'kind': 'zip_hash_mismatch', 'path': rel})
    return problems


