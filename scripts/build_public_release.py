def is_reparse(path):
    """True for symlinks, junctions and other reparse points (and for anything we cannot inspect)."""
    try:
        if os.path.islink(path):
            return True
        isjunction = getattr(os.path, 'isjunction', None)
        if isjunction and isjunction(path):
            return True
        return bool(getattr(os.lstat(path), 'st_file_attributes', 0) & REPARSE_FLAG)
    except OSError:
        return True


def chain_has_link(base, rel):
    cur = base
    for part in rel.split('/'):
        cur = cur / part
        if os.path.lexists(cur) and is_reparse(cur):
            return True
    return False


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, 'rb') as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b''):
            digest.update(chunk)
    return digest.hexdigest()


def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def rel_of(base, path):
    return path.relative_to(base).as_posix()


class Ctx:
    def __init__(self, evidence='always'):
        self.evidence = evidence
        self.selected = {}
        self.excluded = []
        self.skipped = {}
        self.pruned = {}
        self.missing_required = []
        self.optional_absent = []
        self.link_violations = []
        self.oversize = []
        self.unreadable = []
        self.sources = {}  # package path -> repo path, when --override replaces the default source
        self.withheld = []  # package paths removed by --withhold (selected by a rule, deliberately not shipped)

    def count_skip(self, rule_id, rel):
        key = '%s:%s' % (rule_id, _suffix(rel) or '(none)')
        self.skipped[key] = self.skipped.get(key, 0) + 1


def walk_files(ctx, root_rel, recursive=True):
    base = ROOT / root_rel
    if not os.path.lexists(base):
        return
    if chain_has_link(ROOT, root_rel):
        ctx.link_violations.append(root_rel)
        return
    if not base.is_dir():
        return
    for dirpath, dirnames, filenames in os.walk(base, followlinks=False):
        keep = []
        for d in sorted(dirnames):
            full = Path(dirpath) / d
            if is_pruned_dir(d):
                ctx.pruned[d] = ctx.pruned.get(d, 0) + 1
                continue
            if is_reparse(full):
                ctx.link_violations.append(rel_of(ROOT, full))
                continue
            keep.append(d)
        dirnames[:] = keep if recursive else []
        for f in sorted(filenames):
            full = Path(dirpath) / f
            if is_reparse(full):
                ctx.link_violations.append(rel_of(ROOT, full))
                continue
            yield rel_of(ROOT, full)


def admit(ctx, rule, rel):
    reason = deny_reason(rel)
    if reason:
        ctx.excluded.append({'path': rel, 'rule': rule['id'], 'reason': reason})
        return
    if chain_has_link(ROOT, rel):
        ctx.link_violations.append(rel)
        return
    full = ROOT / rel
    try:
        size = full.stat().st_size
        resolved_ok = ROOT in full.resolve().parents
    except OSError:
        ctx.unreadable.append(rel)
        return
    if not resolved_ok:
        ctx.link_violations.append(rel)
        return
    if size > OVERSIZE_ALLOW.get(rel, MAX_FILE_BYTES):
        ctx.oversize.append({'path': rel, 'size': size})
        return
    ctx.selected.setdefault(rel, rule['id'])


def collect(ctx):
    for rule in RULES:
        if rule.get('evidence') and ctx.evidence == 'none':
            continue
        found_exact = []
        for rel in rule.get('exact', ()):
            if os.path.lexists(ROOT / rel):
                if rel not in ctx.selected:
                    admit(ctx, rule, rel)
                if rel in ctx.selected:
                    found_exact.append(rel)
            elif rule.get('required'):
                ctx.missing_required.append({'path': rel, 'rule': rule['id']})
            elif rule.get('absence') == 'each':
                ctx.optional_absent.append({'path': rel, 'rule': rule['id']})
        if rule.get('exact') and rule.get('absence') == 'group' and not found_exact:
            ctx.optional_absent.append({'rule': rule['id'], 'paths': list(rule['exact'])})
        for root in rule.get('roots', ()):
            count = 0
            for rel in walk_files(ctx, root, rule.get('recursive', True)):
                if rel in SUPERSEDED_EXCLUDE_FILES:
                    ctx.excluded.append({'path': rel, 'rule': rule['id'], 'reason': 'superseded'})
                    continue
                if rel.startswith(tuple(rule.get('exclude_prefixes', ()))):
                    ctx.excluded.append({'path': rel, 'rule': rule['id'], 'reason': 'excluded_prefix'})
                    continue
                if not rule['match'](rel):
                    if rule.get('list_skipped'):
                        ctx.excluded.append({'path': rel, 'rule': rule['id'], 'reason': 'not_in_allowlist'})
                    else:
                        ctx.count_skip(rule['id'], rel)
                    continue
                before = len(ctx.selected)
                admit(ctx, rule, rel)
                if len(ctx.selected) > before or rel in ctx.selected:
                    count += 1
            if count < rule.get('min_per_root', 0):
                ctx.missing_required.append({'path': root + '/', 'rule': rule['id'],
                                             'reason': 'fewer than %d allowlisted files' % rule['min_per_root']})


def apply_withholds(ctx, paths):
    """--withhold PKG: do not ship an already-selected path (e.g. a web file not yet deployed)."""
    for pkg in paths or ():
        pkg = pkg.strip().replace('\\', '/')
        if pkg not in ctx.selected:
            raise ValueError('withhold target is not selected by any rule: %s' % pkg)
        del ctx.selected[pkg]
        ctx.withheld.append(pkg)


def apply_overrides(ctx, specs):
    """--override PKG=SRC: ship repo file SRC at the already-selected package path PKG."""
    for spec in specs or ():
        if '=' not in spec:
            raise ValueError('bad --override (expected PKG=SRC): %s' % spec)
        pkg, src = (s.strip().replace('\\', '/') for s in spec.split('=', 1))
        bad_start = ('/', '.')
        if not pkg or not src or pkg.startswith(bad_start) or src.startswith(bad_start) \
                or ':' in pkg + src or '/../' in '/%s/' % src or '/../' in '/%s/' % pkg:
            raise ValueError('override paths must be plain repo-relative posix paths: %s' % spec)
        if pkg not in ctx.selected:
            raise ValueError('override target is not selected by any rule: %s' % pkg)
        if pkg in ctx.sources:
            raise ValueError('duplicate override for %s' % pkg)
        if _suffix(src) != _suffix(pkg):
            raise ValueError('override source must keep the target suffix: %s' % spec)
        reason = deny_reason(src)
        if reason:
            raise ValueError('override source denied (%s): %s' % (reason, src))
        full = ROOT / src
        if chain_has_link(ROOT, src) or not full.is_file() or ROOT not in full.resolve().parents:
            raise ValueError('override source missing, linked or outside the repo: %s' % src)
        if full.stat().st_size > MAX_FILE_BYTES:
            raise ValueError('override source oversize: %s' % src)
        ctx.sources[pkg] = src


def source_of(ctx, rel):
    return ROOT / ctx.sources.get(rel, rel)


