# Verification of a package directory
# ---------------------------------------------------------------------------------------------
def list_package(pkg_dir, problems):
    files = {}
    for dirpath, dirnames, filenames in os.walk(pkg_dir, followlinks=False):
        for d in list(dirnames):
            full = Path(dirpath) / d
            if is_reparse(full):
                problems.append({'kind': 'link_in_package', 'path': rel_of(pkg_dir, full)})
                dirnames.remove(d)
        for f in filenames:
            full = Path(dirpath) / f
            rel = rel_of(pkg_dir, full)
            if is_reparse(full):
                problems.append({'kind': 'link_in_package', 'path': rel})
                continue
            files[rel] = full
    return files


def verify_package(pkg_dir, allow, deep=True, strict_links=False, zip_path=None):
    problems = []
    result = {'package': str(pkg_dir), 'ok': False, 'problems': problems}
    manifest_path = pkg_dir / MANIFEST_NAME
    if not manifest_path.is_file():
        problems.append({'kind': 'manifest_missing'})
        return result
    try:
        manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    except ValueError:
        problems.append({'kind': 'manifest_invalid_json'})
        return result
    if manifest.get('generator') != GENERATOR or manifest.get('schema') != SCHEMA:
        problems.append({'kind': 'manifest_not_from_this_tool'})
        return result
    entries = manifest.get('files', [])
    if not isinstance(entries, list) or any(not isinstance(e, dict) or not isinstance(e.get('path'), str) or not isinstance(e.get('sha256'), str) or not isinstance(e.get('size'), int) for e in entries):
        problems.append({'kind': 'manifest_invalid_entries'})
        return result
    if len({e['path'] for e in entries}) != len(entries):
        problems.append({'kind': 'manifest_duplicate_paths'})
        return result
    expected = {e['path']: e for e in entries}
    actual = list_package(pkg_dir, problems)
    sums_path = pkg_dir / SUMS_NAME
    for rel in sorted(set(expected) - set(actual)):
        problems.append({'kind': 'missing_file', 'path': rel})
    for rel in sorted(set(actual) - set(expected) - {MANIFEST_NAME, SUMS_NAME}):
        problems.append({'kind': 'extra_file', 'path': rel})
    for rel in sorted(set(expected) & set(actual)):
        if sha256_file(actual[rel]) != expected[rel]['sha256']:
            problems.append({'kind': 'hash_mismatch', 'path': rel})
    if not sums_path.is_file():
        problems.append({'kind': 'sums_missing'})
    else:
        entries = [dict(e) for e in expected.values()]
        entries.append({'path': MANIFEST_NAME, 'sha256': sha256_file(manifest_path)})
        if sums_path.read_text(encoding='utf-8') != sums_text(entries):
            problems.append({'kind': 'sums_mismatch'})
    if manifest.get('content_digest_sha256') != content_digest(list(expected.values())):
        problems.append({'kind': 'content_digest_mismatch'})
    if deep:
        for rel in sorted(expected):
            if rel in ('.gitignore', '.gitattributes'):
                want = SAFE_GITIGNORE if rel == '.gitignore' else SAFE_GITATTRIBUTES
                if rel in actual and actual[rel].read_text(encoding='utf-8') != want:
                    problems.append({'kind': rel[1:] + '_not_generated', 'path': rel})
                continue
            reason = deny_reason(rel)
            if reason:
                problems.append({'kind': 'denied', 'path': rel, 'rule': reason})
            elif rule_for(rel) is None:
                problems.append({'kind': 'not_in_allowlist', 'path': rel})
        findings = scan_files(((r, p) for r, p in sorted(actual.items())
                               if r not in (MANIFEST_NAME, SUMS_NAME)), allow)
        result['scan'] = findings
        for f in blocked(findings):
            problems.append({'kind': 'secret_scan_blocked', 'path': f['path'], 'rule': f['rule'],
                             'lines': f['lines']})
    md = [(r, p) for r, p in sorted(actual.items()) if r.endswith('.md')]
    links = check_links(md, set(actual))
    result['links'] = links
    if strict_links and links['missing']:
        problems.append({'kind': 'missing_links', 'count': len(links['missing'])})
    if zip_path is not None:
        zexpected = {r: expected[r]['sha256'] for r in expected}
        zexpected[MANIFEST_NAME] = sha256_file(manifest_path)
        zexpected[SUMS_NAME] = sha256_file(sums_path) if sums_path.is_file() else ''
        zp = verify_zip(zip_path, zexpected)
        problems.extend(zp)
        result['zip_sha256'] = sha256_file(zip_path) if os.path.isfile(zip_path) else None
    result['ok'] = not problems
    return result


