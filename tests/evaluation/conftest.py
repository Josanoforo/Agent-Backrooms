def build_synthetic_report(
    run_id: str,
    model: str,
    levels: dict[str, dict[str, Any]],
    *,
    sandbox_memory: str = "256m",
    marker: bool = True,
    hash_mode: str | None = None,  # None | "valid" | "wrong"
    status: str = "completed",
    run_overrides: dict[str, Any] | None = None,
    usage: Any = None,
    effective_sandbox: dict[str, Any] | None = None,
    experiment_overrides: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Reporte SINTETICO con la forma de /report?format=json.

    Cada nivel: outcome, durations (lista de ms o None por recibo), memory_peak,
    available, evidence, cleanup, oom, receipt_outcomes, measurement y, opcional,
    sandbox_profile / fresh_sandbox_profile (perfil efectivo observado sintetico).
    ``usage`` es el objeto ``usage`` de nivel superior (omitido si es None).
    """
    receipts: list[dict[str, Any]] = []
    summary: dict[str, Any] = {}
    for level, spec in levels.items():
        durations = spec.get("durations", [10])
        outcomes = spec.get("receipt_outcomes") or (
            ["exhausted"] * (len(durations) - 1) + [spec.get("outcome", "exhausted")]
        )
        for step, (dur, rec_outcome) in enumerate(zip(durations, outcomes), start=1):
            receipts.append(
                {
                    "id": f"SYNTHETIC-receipt-{run_id}-{level}-{step}",
                    "run_id": run_id,
                    "level": level,
                    "step": step,
                    "tool": "run_shell",
                    "args": {"command": "SYNTHETIC"},
                    "stdout": "",
                    "stderr": "",
                    "exit_code": 0,
                    "duration_ms": dur,
                    "memory_peak_bytes": spec.get("memory_peak"),
                    "outcome": rec_outcome,
                    "evidence": "SYNTHETIC",
                    "timestamp": "2000-01-01T00:00:00+00:00",
                }
            )
        measurement = spec.get(
            "measurement",
            {"source": "synthetic_source_a", "scope": "level_container", "kind": "peak",
             "available": spec.get("available", True)},
        )
        summary[level] = {
            "outcome": spec.get("outcome", "exhausted"),
            "evidence": spec.get("evidence", "SYNTHETIC evidence"),
            "cleanup_confirmed": spec.get("cleanup", True),
            "oom_killed": spec.get("oom", False),
            "memory_peak_bytes": spec.get("memory_peak"),
            "memory_observed_max_bytes": spec.get("memory_observed_max"),
            "memory_measurement": measurement,
        }
        for field in ("sandbox_profile", "fresh_sandbox_profile", "sandbox_containment"):
            if field in spec:
                summary[level][field] = spec[field]
    run ={"id": run_id, "status": status, "model": model, "levels": list(levels),
           "receipts": receipts, "summary": summary}
    run.update(run_overrides or {})
    doc: dict[str, Any] = {
        "run": run,
        "experiment": {
            "version": "synthetic-0",
            "provider": "SYNTHETIC provider (no real call)",
            "max_steps_per_level": 8,
            "per_level_timeout_seconds": 90,
            "tool_timeout_seconds": 10,
            "output_limit_bytes": 4096,
            "sandbox": {"image": "synthetic-image", "network": "none", "memory": sandbox_memory,
                        "cpus": 1, "pids": 64, "read_only": True},
            "limitations": "SYNTHETIC",
        },
    }
    doc["experiment"].update(experiment_overrides or {})
    if usage is not None:
        doc["usage"] = usage
    if effective_sandbox is not None:
        doc["effective_sandbox"] = effective_sandbox
    if marker:
        doc["synthetic_fixture"] = True
        doc["fixture_notice"] = "SYNTHETIC FIXTURE - NOT EVIDENCE - generated by tests/evaluation"
    if hash_mode:
        body = {k: v for k, v in doc.items()}
        digest = hashlib.sha256(
            json.dumps(body, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
        ).hexdigest()
        doc["sha256"] = digest if hash_mode == "valid" else "0" * 64
    return doc


